import { tokens, type ThemeName } from "./index";

/** Ovis consumes concrete colors for both CSS and the canvas-based terminal. */
export function ovisTheme(name: ThemeName) {
  const c = tokens.colors[name],
    status = tokens.status;
  const vars: Record<string, string> = {
    bg: c.bg,
    "bg-panel": c.paper,
    "bg-elevated": c.surface,
    "bg-hover": c["hover-bg"],
    "bg-input": c.surface,
    border: c.line,
    "border-strong": c["selected-line"],
    text: c.ink,
    "text-dim": c.muted,
    "text-strong": c["primary-ink"],
    accent: c.accent,
    "accent-tint": c["selected-bg"],
    primary: c["primary-bg"],
    "primary-hover": c["primary-line"],
    "primary-text": c["primary-ink"],
    "primary-tint": c["selected-bg"],
    "status-idle": c.muted,
    "status-working": status.working,
    "status-blocked": status.danger,
    "status-done": status.success,
    "status-working-tint": c["selected-bg"],
    "status-blocked-tint": "#382126",
    "status-done-tint": "#173426",
    "danger-tint": "#382126",
    "danger-text": "#ffd9d4",
    notice: status.warning,
    "notice-tint": "#30271b",
    scrim: "rgba(0, 0, 0, 0.6)",
    "term-bg": c.bg,
    "term-fg": c.ink,
    "term-cursor": c.accent,
    "term-selection": c["highlight-bg"],
    "line-number": c.muted,
    "syntax-function": c.accent,
    "syntax-keyword": tokens.syntax.keyword,
    "syntax-string": tokens.syntax.string,
    "syntax-number": tokens.syntax.number,
    "syntax-type": tokens.syntax.type,
    "syntax-variable": c.ink,
    "syntax-meta": tokens.syntax.meta,
    "bubble-border": c["selected-line"],
    "shadow-drawer": "0 0 40px rgba(0, 0, 0, 0.6)",
    "shadow-pop": "0 16px 48px rgba(0, 0, 0, 0.55), 0 0 0 1px var(--border)",
    "shadow-card": "0 4px 16px rgba(0, 0, 0, 0.35)",
    "indicator-working": status.warning,
    "indicator-blocked": status.danger,
    "indicator-done": status.success,
    "indicator-idle": c.muted,
    "indicator-unknown": c.muted,
  };
  return {
    id: `st-${name}`,
    mode: "dark" as const,
    bg: c.bg,
    bgPanel: c.paper,
    vars,
    terminal: {
      background: c.bg,
      foreground: c.ink,
      cursor: c.accent,
      selectionBackground: c["highlight-bg"],
    },
    preview: {
      elevated: c.surface,
      border: c.line,
      text: c.ink,
      textDim: c.muted,
      accent: c.accent,
      primary: c["primary-bg"],
    },
  };
}
