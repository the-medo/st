import { tokens } from "./tokens";
export { tokens };
export type ThemeName = keyof typeof tokens.colors;
export type ThemeColors = { [K in keyof typeof tokens.colors.console]: string };
export function themeName(workmode: boolean): ThemeName {
  return workmode ? "workmode" : "console";
}
export function themeVariables(name: ThemeName): Record<string, string> {
  return Object.fromEntries([
    ...Object.entries(tokens.colors[name]).map(([key, value]) => [
      `--st-${key}`,
      value,
    ]),
    ...Object.entries(tokens.typography).map(([key, value]) => [
      `--st-font-${key}`,
      value,
    ]),
    ...Object.entries(tokens.radius).map(([key, value]) => [
      `--st-radius-${key}`,
      value,
    ]),
    ...Object.entries(tokens.space).map(([key, value]) => [
      `--st-space-${key}`,
      value,
    ]),
    ...Object.entries(tokens.status).map(([key, value]) => [
      `--st-${key}`,
      value,
    ]),
  ]);
}
const declarations = (values: Record<string, string>) =>
  Object.entries(values)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join("\n");
export function themeCss(): string {
  const aliases = Object.fromEntries(
    Object.keys(tokens.colors.console).map((key) => [
      `--${key}`,
      `var(--st-${key})`,
    ]),
  );
  return `/* Generated by @st/theme. Edit tokens.ts and run bun run theme:build. */\n:where(:root, .st-app, [data-st-theme]) {\n${declarations({ ...themeVariables("console"), ...aliases, "--mono": "var(--st-font-mono)", "--radius": "var(--st-radius-panel)" })}\n}\n:where([data-workmode="true"], [data-st-theme="workmode"]) {\n${declarations(themeVariables("workmode"))}\n}\n`;
}
