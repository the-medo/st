#!/usr/bin/env python3
"""Export the Seam source and synchronize the S.T. applications' brand assets."""

import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "brand"
INK, IVORY = "#191918", "#f6f2ea"
WEB_TARGETS = (ROOT / "sm-manager/frontend/public", ROOT / "sm-manager/sm_manager/static")
PANEL = ROOT / "stapp/apps/kiosk/src/assets/brand"


def svg(paths, foreground, background=None, adaptive=False):
    lines = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">',
             '  <title>S.T. — Seam</title>',
             '  <!-- Generated by scripts/generate-brand.py from brand/st-seam.svg. -->']
    if adaptive:
        lines += ['  <style>', f'    .tile {{ fill: {IVORY}; }} .mark {{ fill: {INK}; }}',
                  f'    @media (prefers-color-scheme: dark) {{ .tile {{ fill: {INK}; }} .mark {{ fill: {IVORY}; }} }}',
                  '  </style>']
    if background:
        lines.append(f'  <rect class="tile" width="256" height="256" rx="48" fill="{background}"/>')
    lines += [f'  <g class="mark" fill="{foreground}">', *paths, '  </g>', '</svg>', '']
    return '\n'.join(lines).encode()


def raster(source, size):
    return subprocess.check_output(['rsvg-convert', '--width', str(size), '--height', str(size)], input=source)


def ico(source):
    # Windows supports PNG-compressed ICO entries, including the 256px entry.
    sizes = (16, 24, 32, 48, 64, 128, 256)
    images = [raster(source, size) for size in sizes]
    offset = 6 + 16 * len(sizes)
    entries = []
    for size, image in zip(sizes, images):
        entries.append(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(image), offset))
        offset += len(image)
    return struct.pack('<HHH', 0, 1, len(sizes)) + b''.join(entries) + b''.join(images)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raster', action='store_true', help='Regenerate PNG/ICO exports with rsvg-convert (librsvg)')
    parser.add_argument('--check', action='store_true', help='Report stale assets without writing files')
    args = parser.parse_args()
    if args.raster and not shutil.which('rsvg-convert'):
        parser.error('--raster requires rsvg-convert (librsvg)')
    source = ET.parse(BRAND / 'st-seam.svg').getroot()
    paths = [f'    <path d="{path.attrib["d"]}"/>' for path in source.iter('{http://www.w3.org/2000/svg}path')]
    if source.attrib.get('viewBox') != '0 0 256 256' or len(paths) != 2:
        parser.error('Expected the two Seam paths in a 256 × 256 source')
    vectors = {
        'st-logo-light.svg': svg(paths, INK),
        'st-logo-dark.svg': svg(paths, IVORY),
        'favicon-light.svg': svg(paths, INK, IVORY),
        'favicon-dark.svg': svg(paths, IVORY, INK),
        'favicon.svg': svg(paths, INK, IVORY, adaptive=True),
    }
    outputs = {BRAND / name: data for name, data in vectors.items()}
    raster_specs = {
        'st-logo-light.png': ('st-logo-light.svg', 1024),
        'st-logo-dark.png': ('st-logo-dark.svg', 1024),
        'st-icon-light.png': ('favicon-light.svg', 512),
        'st-icon-dark.png': ('favicon-dark.svg', 512),
        'favicon.png': ('favicon-light.svg', 32),
        'apple-touch-icon.png': ('favicon-light.svg', 180),
        'st-tray.png': ('favicon-light.svg', 64),
    }
    binaries = {}
    for name, (vector, size) in raster_specs.items():
        binaries[name] = raster(vectors[vector], size) if args.raster else (BRAND / name).read_bytes()
    binaries['favicon.ico'] = ico(vectors['favicon-light.svg']) if args.raster else (BRAND / 'favicon.ico').read_bytes()
    outputs.update({BRAND / name: data for name, data in binaries.items()})
    for target in WEB_TARGETS:
        outputs.update({target / name: data for name, data in vectors.items()})
        outputs[target / 'st-logo.svg'] = vectors['st-logo-dark.svg']  # Existing integrations use this URL on dark surfaces.
        outputs.update({target / name: binaries[name] for name in ('favicon.png', 'favicon.ico', 'apple-touch-icon.png')})
    # Imported by Vite: hashed and precached with the faceplate's offline shell.
    outputs.update({PANEL / name: vectors[name] for name in ('st-logo-light.svg', 'st-logo-dark.svg', 'favicon.svg')})
    outputs[PANEL / 'apple-touch-icon.png'] = binaries['apple-touch-icon.png']
    outputs[ROOT / 'stapp/runtime/st-icon.png'] = binaries['st-tray.png']
    outputs[ROOT / 'stapp/deploy/windows/st-icon.ico'] = binaries['favicon.ico']
    outputs[ROOT / 'favicon.svg'] = vectors['favicon.svg']
    stale = [path for path, data in outputs.items() if not path.is_file() or path.read_bytes() != data]
    if args.check:
        for path in stale:
            print(f'Stale: {path.relative_to(ROOT)}')
        if stale:
            raise SystemExit(1)
        print(f'{len(outputs)} brand assets are current.')
    else:
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(outputs[path])
        print(f'Updated {len(stale)} of {len(outputs)} brand assets.')


if __name__ == '__main__':
    main()
